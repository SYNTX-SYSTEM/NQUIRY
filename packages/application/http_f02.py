class _Rejected(Exception):
    def __init__(self, reason_code: str) -> None:
        self.reason_code = reason_code
        super().__init__(reason_code)


def _denied(reason: str, status: int = 403) -> Response:
    return status, {"kind": "denied", "reasonCode": reason}


def _rejected(reason: str) -> Response:
    return 400, {"kind": "rejected", "reasonCode": reason}


def _uuid(value: str, field: str) -> uuid.UUID:
    try:
        return uuid.UUID(value)
    except (ValueError, TypeError) as exc:
        raise _Rejected(f"MALFORMED_{field.upper()}") from exc


def _idempotency(key: str | None) -> tuple[CommandId, str]:
    if not key:
        raise _Rejected("IDEMPOTENCY_KEY_REQUIRED")
    command_uuid = _uuid(key, "idempotency_key")
    return CommandId(command_uuid), str(command_uuid)


def _with_actor(
    session_token: str | None, work: Callable[[GovernedPorts, Any], Response]
) -> Response:
    """Runs `work` inside ONE request transaction (committed on clean
    return). Identity only from the verified HttpOnly session."""
    try:
        with connect() as connection:
            principal = resolve_session(
                session_token,
                session_repository=SqlAlchemyLocalSessionRepository(connection),
                now=datetime.now(timezone.utc),
            )
            if principal is None:
                return _denied("NO_VALID_SESSION", 401)
            return work(GovernedPorts(connection), principal)
    except _Rejected as exc:
        return _rejected(exc.reason_code)


def _command_outcome(run: Callable[[], Response]) -> Response:
    """Maps every governed-Command exception to its distinct envelope kind."""
    try:
        return run()
    except _Rejected as exc:
        return _rejected(exc.reason_code)
    except capture.CaptureInputRejected as exc:
        # F03 HD-12: input, never authority. Nothing was stored or altered.
        return _rejected(exc.reason_code)
    except control.SessionVersionStale as exc:
        return 409, {
            "kind": "stale",
            "reasonCode": "STALE_VERSION",
            "expectedVersion": exc.expected,
            "currentVersion": exc.current,
            "currentState": exc.current_state,
        }
    except control.SessionPreconditionUnmet as exc:
        return 422, {"kind": "blocked", "reasonCode": exc.reason_code}
    except (
        control.SessionCommandDenied,
        ChallengeCreationDenied,
        CreateSessionDenied,
        GrantAuthorityBindingDenied,
    ) as exc:
        chain = exc.chain_result
        terminal = chain.proofs[-1] if chain.proofs else None
        return _denied(terminal.reason_code if terminal is not None else "DENIED")
    except CommitDenied as exc:
        reason = exc.boundary_proof.reason_code
        if reason.startswith("STALE_VERSION"):
            return 409, {"kind": "stale", "reasonCode": reason}
        return _denied(reason)
    except (GrantScopeInvalid, GovernanceRightNotGrantableViaGenericGrant) as exc:
        return _rejected(str(exc))
    except control.SessionNotFound:
        return 404, {"kind": "not_found", "reasonCode": "SESSION_NOT_FOUND"}
    except (
        IdempotencyPayloadCollision,
        CommandPayloadConflict,
        CommandTypeMismatch,
        CommandWorkspaceMismatch,
    ):
        # F02 WU-02.12 (FBR-B): the key is the command_id, so any reuse for
        # another payload, Command type or Workspace names a different
        # logical Command (09 §4.3). It is input, not authority: `rejected`.
        return _rejected("IDEMPOTENCY_KEY_REUSED_FOR_DIFFERENT_COMMAND")
    except (IdempotencyInProgress, IdempotencyIndeterminateBlocked):
        return 503, {"kind": "indeterminate", "reasonCode": "PRIOR_ATTEMPT_UNRESOLVED"}
    except CommitFailedPrecommit as exc:
        return 409, {"kind": "failed_precommit", "reasonCode": exc.reason}
    except CommitIndeterminate as exc:
        return 503, {
            "kind": "indeterminate",
            "reasonCode": "COMMIT_OUTCOME_UNPROVEN",
            "blockedTargetRef": str(exc.commit_id.value),
        }


def _query(run: Callable[[], dict[str, object]]) -> Response:
    try:
        return 200, run()
    except queries.QueryDenied as exc:
        return _denied(exc.reason_code)
    except queries.QueryNotFound as exc:
        return 404, {"kind": "not_found", "reasonCode": exc.reason_code}


