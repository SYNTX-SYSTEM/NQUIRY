"""F02 HTTP dispatch + common failure envelope (WU-02.9).

`apps/api/src/nquiry_api/http/inquiry.py` is a thin adapter. Everything
here returns `(status, body)` with a plain JSON body.

COMMON FAILURE ENVELOPE (19 §29 outcome distinctions, 20 §13): each outcome
kind stays distinct on the wire and in the UI.

| kind | HTTP | meaning |
|---|---|---|
| ok | 200 | query result |
| committed | 200 | governed Command committed; body carries the fresh canonical reread |
| denied | 401/403 | identity or authority/boundary denial (reasonCode from the boundary chain) |
| rejected | 400 | malformed or invalid input: never an authority statement |
| stale | 409 | expected version is no longer current; body carries the current version/state |
| blocked | 422 | a lawful precondition is unmet (e.g. no participant yet) |
| failed_precommit | 409 | proven rollback at the effect gate (nothing committed) |
| indeterminate | 503 | commit outcome cannot be proven; no blind retry |
| not_found | 404 | the named object does not exist in this Workspace |

NETWORK_FAILURE is client-side only (no response).

IDEMPOTENCY TRANSPORT: every F02 Command route requires an
`Idempotency-Key` header holding a UUID, generated by the client once per
logical intent. The key is the Command's `command_id` AND its
`idempotency_key`. A retry of the same intent is therefore the same logical
Command (09 §4.3), and after COMMITTED it returns the committed result
without executing again (14 §27). `UI DEBOUNCE ≠ IDEMPOTENCY`.
"""

