def dispatch_workspace_overview(*, session_token: str | None, workspace_id: str) -> Response:
    def work(ports: GovernedPorts, principal: Any) -> Response:
        ws = WorkspaceId(_uuid(workspace_id, "workspace_id"))
        return _query(lambda: queries.workspace_overview(ports, principal, ws))

    return _with_actor(session_token, work)


